package care.zktrident.app.employer

import androidx.compose.foundation.layout.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Modifier
import androidx.compose.ui.unit.dp

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun EmployerTokensScreen(viewModel: EmployerDashboardViewModel, onBack: () -> Unit) {
    var groupId by remember { mutableStateOf("") }
    var employeeId by remember { mutableStateOf("") }
    var familyId by remember { mutableStateOf("") }
    var validUntil by remember { mutableStateOf("") }
    var generated by remember { mutableStateOf(false) }

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("Token Management") },
                navigationIcon = { TextButton(onClick = onBack) { Text("Back") } },
            )
        },
    ) { padding ->
        Column(
            modifier = Modifier.padding(padding).padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(12.dp),
        ) {
            Text("Generate Enrollment Token", style = MaterialTheme.typography.titleMedium)
            Text(
                "Create a one-time enrollment token for an eligible employee. " +
                    "The token authorizes enrollment without exposing PHI to the insurer.",
                style = MaterialTheme.typography.bodySmall,
            )

            OutlinedTextField(value = groupId, onValueChange = { groupId = it }, label = { Text("Group ID") }, modifier = Modifier.fillMaxWidth())
            OutlinedTextField(value = employeeId, onValueChange = { employeeId = it }, label = { Text("Employee ID") }, modifier = Modifier.fillMaxWidth())
            OutlinedTextField(value = familyId, onValueChange = { familyId = it }, label = { Text("Family ID") }, modifier = Modifier.fillMaxWidth())
            OutlinedTextField(value = validUntil, onValueChange = { validUntil = it }, label = { Text("Valid Until (CCYYMMDD)") }, modifier = Modifier.fillMaxWidth())

            Button(
                onClick = {
                    viewModel.generateToken(groupId, employeeId, familyId, validUntil)
                    generated = true
                },
                modifier = Modifier.fillMaxWidth(),
                enabled = groupId.isNotBlank() && employeeId.isNotBlank() && familyId.isNotBlank() && validUntil.length == 8,
            ) {
                Text("Generate Token")
            }

            if (generated) {
                Card(colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.primaryContainer)) {
                    Text(
                        "Token generated successfully. Distribute to employee via secure channel.",
                        modifier = Modifier.padding(12.dp),
                    )
                }
            }
        }
    }
}
