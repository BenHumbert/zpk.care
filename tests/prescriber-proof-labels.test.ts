/**
 * The prescriber dashboard says what prescribing proved (demo screen 9; audit finding A-22).
 *
 * createPrescription generates its proofs in the engine and keeps none of them: nothing is submitted
 * to the ledger and no one outside the engine verifies them. The dashboard said "ZK Proof: Verified"
 * and listed four proofs, one of which (PrescriptionStatus) the route never makes, while leaving out
 * the one it always makes (ProofGate.verifyPrescriber). The list is now built from the keys the route
 * returns, and this test ties those keys to the engine's source.
 */
import fs from 'fs';

const app = fs.readFileSync('dashboard-prescriber/app.js', 'utf-8').replace(/\r\n/g, '\n');
const engine = fs.readFileSync('src/adjudication/interactive-service.ts', 'utf-8').replace(/\r\n/g, '\n');
const FN = '  function prescribeProofSummary(';
// the proofs' names, which the result box's timings use too (tests/prescriber-result-box.test.ts)
const NAMES = '  var PRESCRIBE_PROOF_NAMES = {';

/** The dashboard's summary function and the names it reads, lifted out of the page and run in Node. */
function loadSummary(): (result: unknown) => string {
  const names = app.indexOf(NAMES);
  expect(names).toBeGreaterThan(-1);
  const start = app.indexOf(FN);
  expect(start).toBeGreaterThan(-1);
  const end = app.indexOf('\n  }\n', start);
  expect(end).toBeGreaterThan(start);
  const namesLine = app.slice(names, app.indexOf('\n', names));
  return new Function(`${namesLine}\n${app.slice(start, end + 4)}\nreturn prescribeProofSummary;`)() as (result: unknown) => string;
}

/** The keys of proofTimesMs in createPrescription's result, read out of the engine's source. */
function prescribeProofKeys(): string[] {
  const fn = engine.indexOf('  async createPrescription(');
  expect(fn).toBeGreaterThan(-1);
  const open = engine.indexOf('proofTimesMs: {', fn) + 'proofTimesMs: {'.length;
  const body = engine.slice(open, engine.indexOf('\n      },', open));
  return [...body.matchAll(/(\w+):/g)].map((m) => m[1]).filter((k) => k !== 'total');
}

describe('the prescriber dashboard after the prescribe proofs finish', () => {
  test('does not say they were verified, and lists no proof the route never makes', () => {
    expect(app).not.toContain('ZK Proof: Verified');
    expect(app).not.toContain('Prescription ZK proof verified');
    expect(app).not.toContain('PrescriptionStatus');
    // The class stays: the demo director waits on badge-settled (tools/demo/director.mjs).
    expect(app).toContain("badge.className = 'badge badge-settled'; badge.textContent = 'ZK Proofs: Generated';");
  });

  test('names the proofs the route generated and says none is kept', () => {
    const summary = loadSummary();
    expect(summary({ proofTimesMs: { proofGate: 1, eligibility: 2, accessControl: 3, messaging: 4, total: 10 } }))
      .toBe('4 ZK proofs generated by the engine: ProofGate.verifyPrescriber + Eligibility + FormularyAccess + Messaging (eScript). Not kept and not sent to the ledger, so no one outside the engine verifies them yet.');
    expect(summary({ proofTimesMs: { proofGate: 1, eligibility: 2, accessControl: 3, priorAuth: 4, messaging: 5, total: 15 } }))
      .toMatch(/^5 ZK proofs generated by the engine: .* \+ PriorAuth \+ /);
    expect(summary(undefined))
      .toBe('ZK proofs generated by the engine. Not kept and not sent to the ledger, so no one outside the engine verifies them yet.');
  });

  test('has a name for every proof key the engine returns, and no other', () => {
    const keys = prescribeProofKeys();
    expect(keys).toContain('proofGate');
    const start = app.indexOf(NAMES);
    expect(start).toBeGreaterThan(-1);
    const named = [...app.slice(start, app.indexOf('};', start)).matchAll(/(\w+): '/g)].map((m) => m[1]);
    expect([...named].sort()).toEqual([...keys].sort());
  });
});
